// TypeScript output. Contracts become runtime checks (requires at entry,
// ensures at every return, where at every construction); examples become an
// exported list the toolchain runs.
//
// Effects leave one trace: a function with effects is an `async` function,
// and every call to one is awaited. alang itself has no asynchronous calls
// (each call ends before the next statement), but most host operations that
// effects stand for (network, waiting) exist only asynchronously. Pure code
// cannot call effectful code (2.1, 2.4, 5.4), so pure functions, lambdas,
// conditions and examples stay synchronous.
//
// The emitter runs only on programs the checker accepted, and uses the
// checker's side tables for expression types (Int vs Float operations) and
// for how names resolved.

import type { Definition, Expr, FnDef, Path, Pattern, Stmt, TypeDef, TypeRef } from "./ast.ts";
import { moduleOf, pathText } from "./ast.ts";
import type { CheckInfo } from "./check.ts";
import { AlangError, diagnostic } from "./diagnostic.ts";
import { FLOAT, INT, isCon, STRING, type Type, typeEquals } from "./types.ts";
import { printExpr } from "./printer.ts";

export interface EmitOptions {
  // Module specifier the generated file uses to import the runtime library.
  readonly runtimeImport: string;
}

const RT = "$rt";

const BUILTIN_VALUES = new Set(["Ok", "Err", "Some", "None", "Unit", "Less", "Equal", "Greater"]);

// Words a local cannot be called in TypeScript; such locals get a `$` suffix.
// Globals are joined with `$` and so never collide with these or with locals.
const RESERVED = new Set(
  ("break case catch class const continue debugger default delete do else enum export extends false finally for " +
    "function if import in instanceof new null return super switch this throw true try typeof var void while with " +
    "yield let static implements interface package private protected public await arguments eval undefined").split(" "),
);

export function mangle(path: Path): string {
  return path.join("$");
}

function local(name: string): string {
  return RESERVED.has(name) ? `${name}$` : name;
}

type Sink =
  | { readonly kind: "discard" }
  | { readonly kind: "return" }
  | { readonly kind: "assign"; readonly target: string }
  | { readonly kind: "push"; readonly target: string };

const DISCARD: Sink = { kind: "discard" };

class Scope {
  private readonly names = new Map<string, string>();
  constructor(private readonly parent: Scope | null = null) {}
  child(): Scope {
    return new Scope(this);
  }
  add(name: string, ts = local(name)): string {
    this.names.set(name, ts);
    return ts;
  }
  lookup(name: string): string | undefined {
    return this.names.get(name) ?? this.parent?.lookup(name);
  }
}

export function emitProgram(defs: readonly Definition[], info: CheckInfo, options: EmitOptions): string {
  const out: string[] = [
    "// Generated by alang. Do not edit.",
    `import * as ${RT} from ${JSON.stringify(options.runtimeImport)};`,
    "",
  ];
  const examples: string[] = [];
  for (const def of defs) {
    const e = new DefinitionEmitter(def, info);
    out.push(...(def.kind === "fn" ? e.fn(def) : e.type(def)), "");
    if (def.kind === "fn") examples.push(...e.examples(def));
  }
  out.push(`export const $examples: readonly ${RT}.Example[] = [`, ...examples.map((e) => `  ${e},`), "];", "");
  return out.join("\n");
}

class DefinitionEmitter {
  private readonly module: Path;
  private readonly name: string;
  private temps = 0;

  constructor(def: Definition, private readonly info: CheckInfo) {
    this.module = moduleOf(def.path);
    this.name = pathText(def.path);
  }

  private fail(code: string, message: string, at: string): never {
    throw new AlangError(diagnostic({ code, definition: this.name, at, message }));
  }

  private temp(prefix: string): string {
    return `$${prefix}${++this.temps}`;
  }

  // A path as written, resolved to its full name: short names belong to the
  // current module (rule 1.2).
  private resolve(path: Path): Path {
    return path.length === 1 ? [...this.module, path[0]] : path;
  }

  private binary(e: Extract<Expr, { kind: "binary" }>, scope: Scope): string {
    const l = this.expr(e.left, scope);
    const r = this.expr(e.right, scope);
    const t = this.typeOf(e.left);
    switch (e.op) {
      case "and":
        return `(${l} && ${r})`;
      case "or":
        return `(${l} || ${r})`;
      case "==":
      case "!=": {
        // Primitives compare natively; everything else structurally (3.9).
        const primitive = t.k === "con" && t.args.length === 0 &&
          ["Int", "Float", "Bool", "String", "Unit"].includes(t.name);
        // Through a function, since TypeScript rejects `===` on operands it
        // has narrowed to different literals (`1 === 2`).
        if (primitive) return `${e.op === "!=" ? "!" : ""}${RT}.same(${l}, ${r})`;
        return `${e.op === "!=" ? "!" : ""}${RT}.eq(${l}, ${r})`;
      }
      case "<":
      case "<=":
      case ">":
      case ">=": {
        if (typeEquals(t, STRING)) {
          const name = { "<": "lt", "<=": "le", ">": "gt", ">=": "ge" }[e.op];
          return `${RT}.str_${name}(${l}, ${r})`;
        }
        return `(${l} ${e.op} ${r})`;
      }
      default: {
        const kind = typeEquals(t, INT) ? "int" : typeEquals(t, FLOAT) ? "float" : null;
        if (kind === null) throw new Error(`arithmetic on unchecked type in ${this.name}`);
        const name = { "+": "add", "-": "sub", "*": "mul", "/": "div", "%": "rem" }[e.op];
        // The trap names the definition, as those of contracts and `match` do.
        return `${RT}.${kind}_${name}(${l}, ${r}, ${JSON.stringify(this.name)})`;
      }
    }
  }

  private typeOf(e: Expr): Type {
    const t = this.info.types.get(e);
    if (!t) throw new Error(`expression without type in ${this.name}: ${printExpr(e, "")}`);
    return t;
  }

  // ---- types ----

  // TypeScript type of a checker type.
  private tsType(t: Type): string {
    switch (t.k) {
      case "con": {
        const args = t.args.map((a) => this.tsType(a));
        switch (t.name) {
          case "Int":
          case "Float":
            return "number";
          case "Bool":
            return "boolean";
          case "String":
            return "string";
          case "Unit":
          case "Order":
            return `${RT}.${t.name}`;
          case "List":
            // Not `readonly T[]`: `readonly readonly number[][]` is not TypeScript.
            return `ReadonlyArray<${args[0]}>`;
          case "Map":
            return `${RT}.SortedMap<${args.join(", ")}>`;
          case "Option":
          case "Result":
            return `${RT}.${t.name}<${args.join(", ")}>`;
        }
        return this.globalRef(t.name.split("."));
      }
      case "fn":
        return `((${t.params.map((p, i) => `p${i}: ${this.tsType(p)}`).join(", ")}) => ${this.tsType(t.out)})`;
      default:
        throw new Error(`no TypeScript type for ${t.k} in ${this.name}`);
    }
  }

  private ts(t: TypeRef): string {
    // The shape of `tsType`; function values are synchronous, since every
    // one outside std's handler is pure (F3).
    if (t.kind === "function") {
      return `((${t.params.map((p, i) => `p${i}: ${this.ts(p)}`).join(", ")}) => ${this.ts(t.out)})`;
    }
    const args = t.args.map((a) => this.ts(a));
    if (t.path.length === 1) {
      switch (t.path[0]) {
        case "Int":
        case "Float":
          return "number";
        case "Bool":
          return "boolean";
        case "String":
          return "string";
        case "Unit":
          return `${RT}.Unit`;
        case "Order":
          return `${RT}.Order`;
        case "List":
          return `ReadonlyArray<${args[0]}>`;
        case "Map":
          return `${RT}.SortedMap<${args.join(", ")}>`;
        case "Option":
        case "Result":
          return `${RT}.${t.path[0]}<${args.join(", ")}>`;
      }
    }
    const head = this.globalRef(this.resolve(t.path));
    return args.length === 0 ? head : `${head}<${args.join(", ")}>`;
  }

  private globalRef(full: Path): string {
    return full[0] === "std" ? `${RT}.${mangle(full)}` : mangle(full);
  }

  // ---- definitions ----

  type(def: TypeDef): string[] {
    const name = mangle(def.path);
    if (def.shape.kind === "variant") {
      if (def.where) this.fail("E0303", "`where` on a variant type is not supported yet.", printExpr(def.where, ""));
      const cases = def.shape.cases.map((c) =>
        c.payload
          ? `{ readonly tag: ${JSON.stringify(c.name)}; readonly value: ${this.ts(c.payload)} }`
          : `{ readonly tag: ${JSON.stringify(c.name)} }`
      );
      return [`export type ${name} =`, ...cases.map((c, i) => `  | ${c}${i === cases.length - 1 ? ";" : ""}`)];
    }
    const fields = def.shape.fields;
    const lines = [
      `export type ${name} = {`,
      ...fields.map((f) => `  readonly ${f.name}: ${this.ts(f.type)};`),
      "};",
      `export function ${name}($fields: ${name}): ${name} {`,
    ];
    if (def.where) {
      const scope = new Scope();
      const binds = fields.map((f) => {
        const ts = scope.add(f.name);
        return ts === f.name ? ts : `${f.name}: ${ts}`;
      });
      const text = printExpr(def.where, "");
      lines.push(
        `  const { ${binds.join(", ")} } = $fields;`,
        `  if (!(${this.expr(def.where, scope)})) {`,
        `    ${RT}.trap("where", ${JSON.stringify(this.name)}, ${JSON.stringify(text)}, ${
          JSON.stringify(`Invariant of ${this.name} violated: ${text}`)
        });`,
        "  }",
      );
    }
    lines.push("  return $fields;", "}");
    return lines;
  }

  fn(def: FnDef): string[] {
    const scope = new Scope();
    const params = def.params.map((p) => `${scope.add(p.name)}: ${this.ts(p.type)}`);
    const out = this.ts(def.out);
    const async = def.effects.length > 0;
    const promised = async ? `Promise<${out}>` : out;
    const lines = [
      `export ${async ? "async " : ""}function ${mangle(def.path)}(${params.join(", ")}): ${promised} {`,
    ];
    if (def.requires) lines.push(...indent(this.check("requires", def.requires, scope), 1));
    if (def.ensures) {
      const inner = scope.child();
      lines.push(
        `  const result: ${out} = ${async ? "await (async " : "("}(): ${promised} => {`,
        ...indent(this.block(def.body, inner, DISCARD), 2),
        "  })();",
      );
      const ensuresScope = scope.child();
      ensuresScope.add("result", "result");
      lines.push(...indent(this.check("ensures", def.ensures, ensuresScope), 1), "  return result;");
    } else {
      lines.push(...indent(this.block(def.body, scope.child(), DISCARD), 1));
    }
    lines.push("}");
    return lines;
  }

  private check(kind: "requires" | "ensures", cond: Expr, scope: Scope): string[] {
    const text = printExpr(cond, "");
    const what = kind === "requires" ? "Precondition" : "Postcondition";
    return [
      `if (!(${this.expr(cond, scope)})) {`,
      `  ${RT}.trap(${JSON.stringify(kind)}, ${JSON.stringify(this.name)}, ${JSON.stringify(text)}, ${
        JSON.stringify(`${what} of ${this.name} violated: ${text}`)
      });`,
      "}",
    ];
  }

  // Each example `call == expected` as its two sides; the toolchain compares
  // them with structural equality, which is what `==` means on every type (3.9).
  examples(def: FnDef): string[] {
    return def.examples.map((ex) => {
      // The parser guarantees the form (E0105).
      if (ex.kind !== "binary" || ex.op !== "==") throw new Error(`not an example: ${printExpr(ex, "")}`);
      const text = printExpr(ex, "");
      return `{ definition: ${JSON.stringify(this.name)}, text: ${JSON.stringify(text)}, actual: () => ${
        this.expr(ex.left, new Scope())
      }, expected: () => ${this.expr(ex.right, new Scope())} }`;
    });
  }

  // ---- statements ----

  private block(stmts: readonly Stmt[], scope: Scope, sink: Sink): string[] {
    const lines: string[] = [];
    stmts.forEach((s, i) => {
      const last = i === stmts.length - 1;
      lines.push(...this.stmt(s, scope, last ? sink : DISCARD));
      // A statement without a value that ends a block delivers `Unit`, so a
      // `return match` in a `Unit` function returns in every branch.
      const valueless = s.kind === "let" || s.kind === "propagate" || s.kind === "destructure";
      if (last && valueless && sink.kind !== "discard") {
        lines.push(this.applySink(sink, `${RT}.Unit`));
      }
    });
    return lines;
  }

  // Unpacks a `Result` or an `Option` into a fresh constant, returning the
  // `else` value if it is `Err` or `None`. Returns the lines and the constant.
  private unpack(value: Expr, elseReturn: Expr, scope: Scope): [string[], string] {
    const tmp = this.temp("r");
    const elseScope = scope.child();
    const err = elseScope.add("error");
    // `error` is the Err value of a Result, and Unit for an Option.
    const isResult = isCon(this.typeOf(value), "Result");
    return [[
      `const ${tmp} = ${this.expr(value, scope)};`,
      `if (!${RT}.isPresent(${tmp})) {`,
      `  const ${err} = ${isResult ? `${tmp}.value` : `${RT}.Unit`};`,
      `  return ${this.expr(elseReturn, elseScope)};`,
      "}",
    ], tmp];
  }

  private stmt(s: Stmt, scope: Scope, sink: Sink): string[] {
    switch (s.kind) {
      case "let": {
        const type = this.ts(s.type);
        if (s.elseReturn) {
          const [lines, tmp] = this.unpack(s.value, s.elseReturn, scope);
          lines.push(`const ${scope.add(s.name)}: ${type} = ${tmp}.value;`);
          return lines;
        }
        if (isBlock(s.value)) {
          // Through a temporary: a pattern or `let` inside the value may bind
          // the same name, since the binding is visible only after it (2.6),
          // and would otherwise take the assignment in TypeScript.
          const target = this.temp("v");
          return [
            `let ${target}: ${type};`,
            ...this.blockExpr(s.value, scope, { kind: "assign", target }),
            `const ${scope.add(s.name)}: ${type} = ${target};`,
          ];
        }
        const value = this.expr(s.value, scope);
        return [`const ${scope.add(s.name)}: ${type} = ${value};`];
      }
      case "propagate":
        return this.unpack(s.value, s.elseReturn, scope)[0];
      case "destructure": {
        // The checker accepted it, so the type is `List<T>`.
        if (s.type.kind !== "type") throw new Error(`destructure without a List type in ${this.name}`);
        const item = this.ts(s.type.args[0]);
        const tmp = this.temp("r");
        const elseScope = scope.child();
        const err = elseScope.add("error");
        return [
          `const ${tmp} = ${this.expr(s.value, scope)};`,
          `if (${tmp}.length !== ${s.names.length}) {`,
          `  const ${err} = ${RT}.Unit;`,
          `  return ${this.expr(s.elseReturn, elseScope)};`,
          "}",
          ...s.names.map((name, i) => `const ${scope.add(name)}: ${item} = ${tmp}[${i}];`),
        ];
      }
      case "return":
        if (isBlock(s.value)) return this.blockExpr(s.value, scope, { kind: "return" });
        return [`return ${this.expr(s.value, scope)};`];
      case "expr":
        if (isBlock(s.expr)) return this.blockExpr(s.expr, scope, sink);
        return [this.applySink(sink, this.expr(s.expr, scope))];
    }
  }

  private applySink(sink: Sink, value: string): string {
    switch (sink.kind) {
      case "discard":
        return `${value};`;
      case "return":
        return `return ${value};`;
      case "assign":
        return `${sink.target} = ${value};`;
      case "push":
        return `${sink.target}.push(${value});`;
    }
  }

  // `if`, `match` and `for` compile to statements that deliver their value
  // into the sink, so a `return` inside them leaves the function.
  private blockExpr(e: Expr, scope: Scope, sink: Sink): string[] {
    switch (e.kind) {
      case "if": {
        const lines = [
          `if (${this.expr(e.cond, scope)}) {`,
          ...indent(this.block(e.then, scope.child(), sink), 1),
        ];
        if (e.else) {
          lines.push("} else {", ...indent(this.block(e.else, scope.child(), sink), 1));
        } else if (sink.kind !== "discard") {
          lines.push("} else {", `  ${this.applySink(sink, `${RT}.Unit`)}`);
        }
        lines.push("}");
        return lines;
      }
      case "match": {
        const subject = this.temp("m");
        const lines = [`const ${subject} = ${this.expr(e.subject, scope)};`];
        // A shared case is one branch per pattern, each with its own binds
        // and its own copy of the body, so TypeScript narrows each (T10).
        e.arms.flatMap((arm) => arm.patterns.map((p) => ({ p, body: arm.body }))).forEach(({ p, body }, i) => {
          const conds: string[] = [];
          const binds: [string, string][] = [];
          this.pattern(p, subject, conds, binds);
          const armScope = scope.child();
          const test = conds.length === 0 ? "true" : conds.join(" && ");
          lines.push(`${i === 0 ? "if" : "} else if"} (${test}) {`);
          for (const [name, access] of binds) lines.push(`  const ${armScope.add(name)} = ${access};`);
          lines.push(...indent(this.block(body, armScope, sink), 1));
        });
        lines.push(
          "} else {",
          `  ${RT}.trap("match", ${JSON.stringify(this.name)}, ${
            JSON.stringify(`match ${printExpr(e.subject, "")}`)
          }, "No case matched.");`,
          "}",
        );
        return lines;
      }
      case "for": {
        const iterable = this.expr(e.iterable, scope);
        const bodyScope = scope.child();
        const head = `for (const ${bodyScope.add(e.name)} of ${iterable}) {`;
        if (sink.kind === "discard") {
          return [head, ...indent(this.block(e.body, bodyScope, DISCARD), 1), "}"];
        }
        const t = this.typeOf(e);
        if (!isCon(t, "List")) throw new Error(`for without a List type in ${this.name}`);
        const list = this.temp("f");
        return [
          `const ${list}: ${this.tsType(t.args[0])}[] = [];`,
          head,
          ...indent(this.block(e.body, bodyScope, { kind: "push", target: list }), 1),
          "}",
          this.applySink(sink, list),
        ];
      }
      default:
        throw new Error(`not a block expression: ${e.kind}`);
    }
  }

  private pattern(p: Pattern, access: string, conds: string[], binds: [string, string][]): void {
    switch (p.kind) {
      case "bind":
        binds.push([p.name, access]);
        return;
      case "literal":
        conds.push(`${RT}.eq(${access}, ${this.expr(p.value, new Scope())})`);
        return;
      case "case":
        conds.push(`${access}.tag === ${JSON.stringify(p.path[p.path.length - 1])}`);
        if (p.sub) this.pattern(p.sub, `${access}.value`, conds, binds);
        return;
    }
  }

  // ---- expressions ----

  private expr(e: Expr, scope: Scope): string {
    switch (e.kind) {
      case "int":
      case "float":
        return e.value < 0 ? `(${e.value})` : String(e.value);
      case "string":
        return JSON.stringify(e.value);
      case "bool":
        return String(e.value);
      case "name": {
        const resolved = this.info.names.get(e);
        if (resolved?.kind === "fn") return this.globalRef(resolved.name.split("."));
        const head = scope.lookup(e.path[0]);
        if (head === undefined) {
          this.fail("E0301", `Unknown name \`${pathText(e.path)}\`.`, pathText(e.path));
        }
        return [head, ...e.path.slice(1)].join(".");
      }
      case "field":
        return `(${this.expr(e.target, scope)}).${e.field}`;
      case "call": {
        const callee = this.globalRef(this.resolve(e.path));
        const typeArgs = e.typeArgs.length === 0 ? "" : `<${e.typeArgs.map((t) => this.ts(t)).join(", ")}>`;
        // Arguments appear in declaration order (rule 4.1), so they map to
        // positional parameters directly.
        const call = `${callee}${typeArgs}(${e.args.map((a) => this.expr(a.value, scope)).join(", ")})`;
        return this.info.effectful.has(e) ? `(await ${call})` : call;
      }
      // Never awaited: every function value outside std's handler is pure
      // (F3), and pure functions are synchronous.
      case "apply":
        return `${this.expr(e.target, scope)}(${e.args.map((a) => this.expr(a, scope)).join(", ")})`;
      case "construct": {
        const last = e.path[e.path.length - 1];
        const builtin = e.path.length === 1 && BUILTIN_VALUES.has(last);
        const p = e.payload;
        if (p !== null && p.kind === "args") {
          const fields = p.args.map((a) => `${a.name}: ${this.expr(a.value, scope)}`);
          return `${this.globalRef(this.resolve(e.path))}({ ${fields.join(", ")} })`;
        }
        if (builtin) {
          return p === null ? `${RT}.${last}` : `${RT}.${last}(${this.expr(p.value, scope)})`;
        }
        const tag = `tag: ${JSON.stringify(last)}`;
        const value = p === null ? `{ ${tag} }` : `{ ${tag}, value: ${this.expr(p.value, scope)} }`;
        // A case has its variant type, not its own: a local of the type must
        // not be narrowed to the case by TypeScript, or a `match` on it would
        // not type-check. `satisfies` keeps the check, `as` widens.
        const construct = this.info.constructs.get(e);
        if (construct?.kind !== "case") throw new Error(`unresolved case: ${pathText(e.path)}`);
        const type = this.globalRef(construct.type.split("."));
        return `(${value} satisfies ${type} as ${type})`;
      }
      case "list": {
        // Annotated with the checked type: TypeScript would infer the items'
        // own type (`Some<number>` for `[Some(1)]`) and reject a `None` later.
        const t = this.typeOf(e);
        if (!isCon(t, "List")) throw new Error(`list literal without a List type in ${this.name}`);
        const type = `ReadonlyArray<${this.tsType(t.args[0])}>`;
        return `([${e.items.map((x) => this.expr(x, scope)).join(", ")}] satisfies ${type} as ${type})`;
      }
      case "map": {
        // With the checked types, for the reason given at `list`. Entries are
        // evaluated from left to right, each key before its value; a key that
        // occurs twice traps.
        const t = this.typeOf(e);
        if (!isCon(t, "Map")) throw new Error(`map literal without a Map type in ${this.name}`);
        const entries = e.entries.map((x) => `[${this.expr(x.key, scope)}, ${this.expr(x.value, scope)}]`);
        return `${RT}.map_literal<${this.tsType(t.args[0])}, ${this.tsType(t.args[1])}>([${entries.join(", ")}], ${
          JSON.stringify(this.name)
        })`;
      }
      case "binary":
        return this.binary(e, scope);
      case "not":
        return `!(${this.expr(e.operand, scope)})`;
      case "lambda": {
        const inner = scope.child();
        const params = e.params.map((p) => `${inner.add(p.name)}: ${this.ts(p.type)}`);
        return `((${params.join(", ")}): ${this.ts(e.out)} => ${this.expr(e.body, inner)})`;
      }
      case "if":
      case "match":
      case "for":
        return this.fail(
          "E0303",
          "`if`, `match` and `for` are supported as a statement, as the value of `let` and after `return`; not inside other expressions yet.",
          printExpr(e, "").split("\n", 1)[0],
        );
    }
  }
}

function isBlock(e: Expr): boolean {
  return e.kind === "if" || e.kind === "match" || e.kind === "for";
}

function indent(lines: readonly string[], levels: number): string[] {
  const pad = "  ".repeat(levels);
  return lines.map((l) => pad + l);
}
